def hitung_sin(x, n):
    hasil = 0
    tabel = []
    for i in range(n):
        suku = (-1)**i * x**(2*i+1) / math.factorial(2*i+1)
        hasil += suku
        tabel.append((suku, hasil))
    return hasil, tabel

def hitung_cos(x, n):
    hasil = 0
    tabel = []
    for i in range(n):
        suku = (-1)**i * x**(2*i) / math.factorial(2*i)
        hasil += suku
        tabel.append((suku, hasil))
    return hasil, tabel

while True:
    x = float(input("Masukkan x (derajat): "))
    n = int(input("Masukkan n (0 untuk berhenti): "))
    if n == 0:
        print("Selesai")
        break
    x = x * math.pi / 180

    sin_hasil, tabel_sin = hitung_sin(x, n)
    cos_hasil, tabel_cos = hitung_cos(x, n)

    print("-" * 60)
    print(f"{'i':<4}{'Suku sin':>14}{'sin':>14}{'Suku cos':>14}{'cos':>14}")
    print("-" * 60)
    for i in range(n):
        s_suku, s_total = tabel_sin[i]
        c_suku, c_total = tabel_cos[i]
        print(f"{i:<4}{s_suku:>14.7f}{s_total:>14.7f}{c_suku:>14.7f}{c_total:>14.7f}")
